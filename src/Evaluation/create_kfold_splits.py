DEFAULT_YAML   = PROJECT_ROOT / "Data" / "Processed" / "scoliosis_cleaned" / "scoliosis_cleaned.yaml"
DEFAULT_OUTPUT = PROJECT_ROOT / "Data" / "Processed" / "kfold_splits"


def resolve_dataset_root(data_yaml: Path) -> Path:
    cfg = yaml.safe_load(data_yaml.read_text(encoding="utf-8")) or {}
    root = Path(cfg["path"]) if cfg.get("path") else data_yaml.parent
    return root if root.is_absolute() else (data_yaml.parent / root).resolve()


def build_groups(records):
    """Group id per record: same source photo OR near-identical pixels -> same group (union-find)."""
    parent = list(range(len(records)))

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    def union(a, b):
        parent[find(a)] = find(b)

    first_of_source = {}
    for i, r in enumerate(records):
        union(i, first_of_source.setdefault(source_key(r["stem"]), i))
    for i, j, _ in near_duplicate_pairs(records):
        union(i, j)

    roots = {}
    return [roots.setdefault(find(i), len(roots)) for i in range(len(records))]


def copy_fold(fold_dir: Path, train_recs, valid_recs):
    for split_name, recs in (("train", train_recs), ("valid", valid_recs)):
        (fold_dir / split_name / "images").mkdir(parents=True, exist_ok=True)
        (fold_dir / split_name / "labels").mkdir(parents=True, exist_ok=True)
        for r in recs:
            shutil.copy2(r["image"], fold_dir / split_name / "images" / r["image"].name)
            shutil.copy2(r["label"], fold_dir / split_name / "labels" / r["label"].name)


def write_fold_yaml(fold_dir: Path, fold_no: int, source_cfg: dict):
    cfg = {
        "path":      str(fold_dir),
        "train":     "train/images",
        "val":       "valid/images",
        "kpt_shape": source_cfg.get("kpt_shape", [12, 3]),
        "flip_idx":  source_cfg.get("flip_idx", list(range(12))),
        "nc":        source_cfg.get("nc", 2),
        "names":     source_cfg.get("names", CLASS_NAMES),
    }
    yaml_path = fold_dir / f"fold_{fold_no}.yaml"
    with open(yaml_path, "w", encoding="utf-8") as f:
        yaml.dump(cfg, f, default_flow_style=False, sort_keys=False, allow_unicode=True)
    return yaml_path


