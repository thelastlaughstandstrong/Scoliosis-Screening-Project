# ============================================================
# Stratified, Group-Aware K-Fold Split Preparation (OPTIONAL)
#
# Prepares k train/valid splits of the cleaned dataset for cross-validated
# evaluation. It does NOT train anything — training k YOLO models is slow on
# CPU (about as long as k separate fine-tuning runs), so that is left to you.
#
# Why k-fold: with ~180 images and a 19-image test set, a single split's
# metrics swing a lot. Averaging over folds shows how stable a result is.
# It is an evaluation-robustness tool, not the main training pipeline.
#
# How the folds are built:
#   - All images (train + valid + test of the cleaned dataset) are pooled, so every
#     image is validated on exactly once.
#   - Stratified by class (normal / scoliosis), so each fold keeps a similar mix.
#   - Grouped: the dataset holds several copies of the same photo (same filename
#     before `.rf.`, or near-identical pixels under a different name). All copies
#     of one photo are kept in the SAME fold, so a photo never appears in both a
#     fold's train and valid sets. (The original train/valid/test split does not
#     guarantee this — see split_quality_check.py.)
#
# Each fold is a self-contained YOLO dataset copied into the output directory:
#   <output-dir>/fold_1/{train,valid}/{images,labels}  +  fold_1/fold_1.yaml
# The original and cleaned datasets are never modified.
#
# Usage:
#   python create_kfold_splits.py
#   python create_kfold_splits.py --k 3 --seed 42 --output-dir Data/Processed/kfold_splits
#   python create_kfold_splits.py --force            (rebuild; replaces fold_* inside --output-dir only)
# ============================================================

