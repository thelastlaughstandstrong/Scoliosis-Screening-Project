def run(data_yaml: Path, k: int, seed: int, output_dir: Path, force: bool):
    data_yaml = data_yaml.resolve()
    output_dir = output_dir.resolve()
    if not data_yaml.exists():
        print(f"[ERROR] data yaml not found: {data_yaml}")
        return 1
    source_cfg = yaml.safe_load(data_yaml.read_text(encoding="utf-8")) or {}
    root = resolve_dataset_root(data_yaml)

    # Never write into a source dataset.
    protected = [root.resolve()] + [p.resolve() for p in DATASETS.values()]
    if any(output_dir == p or p in output_dir.parents or output_dir in p.parents for p in protected):
        print(f"[ERROR] --output-dir must be separate from the source datasets: {output_dir}")
        return 1

    existing = list(output_dir.glob("fold_*")) if output_dir.exists() else []
    if existing and not force:
        print(f"[ERROR] {output_dir} already contains fold folders. Re-run with --force to rebuild them.")
        return 1

    records = [r for s in SPLITS for r in list_split(root, s)]
    usable, skipped = [], []
    for r in records:
        r["class_id"], _, problem = label_summary(r["label"])
        (skipped if r["class_id"] is None or r["label"] is None else usable).append(r)
    if skipped:
        print(f"[INFO] Skipping {len(skipped)} image(s) with no usable label: {[r['stem'][:24] for r in skipped][:5]}")
    if len(usable) < k * 2:
        print(f"[ERROR] Too few usable images ({len(usable)}) for k={k}.")
        return 1

    groups = build_groups(usable)
    y = np.array([r["class_id"] for r in usable])
    sgkf = StratifiedGroupKFold(n_splits=k, shuffle=True, random_state=seed)
    folds = list(sgkf.split(np.zeros(len(usable)), y, groups))

    if force:
        for p in existing:
            shutil.rmtree(p, ignore_errors=True)
        for name in ("README.md", "kfold_manifest.csv"):
            (output_dir / name).unlink(missing_ok=True)
    output_dir.mkdir(parents=True, exist_ok=True)

    fold_rows, manifest_rows = [], []
    for fold_no, (train_idx, valid_idx) in enumerate(folds, start=1):
        train_recs = [usable[i] for i in train_idx]
        valid_recs = [usable[i] for i in valid_idx]
        fold_dir = output_dir / f"fold_{fold_no}"
        copy_fold(fold_dir, train_recs, valid_recs)
        yaml_path = write_fold_yaml(fold_dir, fold_no, source_cfg)

        # Safety checks: no group may straddle train/valid; both classes must be present in valid.
        straddle = {groups[i] for i in train_idx} & {groups[i] for i in valid_idx}
        vc = collections.Counter(usable[i]["class_id"] for i in valid_idx)
        tc = collections.Counter(usable[i]["class_id"] for i in train_idx)
        if straddle:
            print(f"[ERROR] fold {fold_no}: {len(straddle)} photo group(s) appear in both train and valid.")
            return 1
        if len(vc) < 2:
            print(f"[WARN] fold {fold_no}: validation set contains only one class — try another --seed.")

        fold_rows.append({
            "fold": fold_no,
            "train_images": len(train_idx), "valid_images": len(valid_idx),
            "train normal:scoliosis": f"{tc.get(0, 0)}:{tc.get(1, 0)}",
            "valid normal:scoliosis": f"{vc.get(0, 0)}:{vc.get(1, 0)}",
            "valid photo groups": len({groups[i] for i in valid_idx}),
            "yaml": yaml_path.relative_to(PROJECT_ROOT).as_posix() if PROJECT_ROOT in yaml_path.parents else str(yaml_path),
        })
        for i in valid_idx:
            r = usable[i]
            manifest_rows.append({"stem": r["stem"], "original_split": r["split"],
                                  "class": CLASS_NAMES[r["class_id"]], "group_id": groups[i], "valid_in_fold": fold_no})

    fold_table = pd.DataFrame(fold_rows)
    pd.DataFrame(manifest_rows).sort_values(["valid_in_fold", "stem"]).to_csv(output_dir / "kfold_manifest.csv", index=False)
    write_readme(output_dir, k, seed, fold_table.drop(columns=["yaml"]), data_yaml)

    print(f"\n{'='*60}\n  {k}-FOLD SPLITS (stratified, grouped by source photo)\n{'='*60}")
    print(f"  Source : {data_yaml.relative_to(PROJECT_ROOT) if PROJECT_ROOT in data_yaml.parents else data_yaml}")
    print(f"  Images : {len(usable)} usable ({len(set(groups))} distinct photo groups), seed {seed}\n")
    print(fold_table.drop(columns=["yaml"]).to_string(index=False))
    print(f"\n  Output : {output_dir.relative_to(PROJECT_ROOT) if PROJECT_ROOT in output_dir.parents else output_dir}")
    print("  Nothing was trained. See README.md in the output folder for how to train a fold.\n")
    return 0


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Prepare optional stratified, photo-grouped k-fold splits of the cleaned dataset.")
    parser.add_argument("--data-yaml", type=Path, default=DEFAULT_YAML, help="Cleaned dataset yaml (default: scoliosis_cleaned.yaml).")
    parser.add_argument("--k", type=int, default=3, help="Number of folds (default: 3 — the dataset is small and training is slow).")
    parser.add_argument("--seed", type=int, default=42, help="Random seed for the fold assignment (default: 42).")
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT, help="Where to write the folds (default: Data/Processed/kfold_splits).")
    parser.add_argument("--force", action="store_true", help="Rebuild: replace existing fold_* folders inside --output-dir.")
    args = parser.parse_args()
    sys.exit(run(args.data_yaml, args.k, args.seed, args.output_dir, args.force))
